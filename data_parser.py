import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns


short_run_cutoff = 14  # days to maturity cutoff for short run bills
year_day_count = 365.25  # days in a year for annualizing yield


# Treasury security price data parser
variable_names = ['CUSIP', 'SECURITY TYPE', 'RATE', 'MATURITY DATE', 'CALL DATE', 'BUY', 'SELL', 'END OF DAY']

df = pd.read_csv('10-14-26_securityprice.csv', header=None, names=variable_names, index_col=False)
df = df.drop(columns=['CALL DATE', 'END OF DAY'])  # no callable bonds in the sample 
df = df[df['SECURITY TYPE'] != 'TIPS']  # filter out TIPS securities
df = df[df['SECURITY TYPE'] != 'MARKET BASED FRN']  # filter out FRNs securities
df = df[(df['BUY'] > 0) & (df['SELL'] > 0)]  # filter out securities with no price data

# confirm data is loaded correctly
print(df.head())

# EDA for which price data to use
print(df.describe())

# # calcualting time to maturity
start_date = pd.to_datetime('10/14/2026')
df['MATURITY DATE'] = pd.to_datetime(df['MATURITY DATE'], errors='coerce')
df['TIME TO MATURITY'] = (df['MATURITY DATE'] - start_date).dt.days

print(df[['TIME TO MATURITY']].describe())

# calculating price (midpoint of buy and sell)
df['PRICE'] = (df['BUY'] + df['SELL']) / 2 

print(df[['PRICE']].describe())

# isolate just bills
bills = df[df['SECURITY TYPE'] == 'MARKET BASED BILL']

# drop very short term bills (less than short_run_cutoff days to maturity)
bills = bills[bills['TIME TO MATURITY'] >= short_run_cutoff].copy()

# finding annulaized yield for each security
bills['ZERO RATE'] = np.log(100 / bills['PRICE']) * (year_day_count / bills['TIME TO MATURITY'])

print(bills.head())

scatter = sns.scatterplot(data=bills, x="TIME TO MATURITY", y="ZERO RATE")
scatter.set(
    title="Observed Treasury Bill Zero Rates - October 14th, 2026",
    xlabel="Time to Maturity (days)",
    ylabel="Zero Rate (continuously compounded, decimal)"
)
plt.figtext(0.01, 0.02,
            f"Midpoint prices; bills with ≥ {short_run_cutoff} days to maturity (n = {len(bills)})",
            ha="left", va="bottom", fontsize=8)
plt.subplots_adjust(bottom=0.14)

plt.savefig("10-14-26_zero_rates_observed.png")


# Coupon securities (notes and bonds)
min_coupon_maturity_days = 91  # drop coupon securities with < 3 months to maturity (GSW 2007)
max_maturity_years = 11  # keep a little past 10 years so the 10-year point is supported by data
settle_date = start_date  # prices are as of 10/14/2026

coupons = df[df['SECURITY TYPE'].isin(['MARKET BASED NOTE', 'MARKET BASED BOND'])].copy()
coupons = coupons.dropna(subset=['MATURITY DATE'])
coupons = coupons[(coupons['TIME TO MATURITY'] >= min_coupon_maturity_days) &
                  (coupons['TIME TO MATURITY'] <= max_maturity_years * year_day_count)].copy()


def coupon_schedule(maturity, settle):
    """Return (previous coupon date, list of remaining coupon dates) for a semiannual security.

    Dates are generated by stepping back from maturity in 6-month multiples (not chained
    offsets, which would drift). Month-end maturities keep month-end coupons, e.g. 4/30 -> 10/31.
    A coupon falling exactly on the settle date counts as already paid.
    """
    month_end = maturity.is_month_end
    remaining = []
    k = 0
    while True:
        d = maturity - pd.DateOffset(months=6 * k)
        if month_end:
            d = d + pd.offsets.MonthEnd(0)
        if d <= settle:
            return d, remaining[::-1]
        remaining.append(d)
        k += 1


def cash_flow_record(rate, maturity, settle):
    """Cash flows (per 100 face), times in years, and actual/actual accrued interest."""
    prev_coupon, dates = coupon_schedule(maturity, settle)
    coupon = rate * 100 / 2
    amounts = np.full(len(dates), coupon)
    amounts[-1] += 100  # principal repaid with the final coupon
    times = np.array([(d - settle).days for d in dates]) / year_day_count
    next_coupon = dates[0]
    accrued = coupon * (settle - prev_coupon).days / (next_coupon - prev_coupon).days
    return {'PREV COUPON': prev_coupon, 'NEXT COUPON': next_coupon, 'N CASH FLOWS': len(dates),
            'CF TIMES': times, 'CF AMOUNTS': amounts, 'ACCRUED': accrued}


records = [cash_flow_record(r, m, settle_date) for r, m in zip(coupons['RATE'], coupons['MATURITY DATE'])]
coupons = coupons.join(pd.DataFrame(records, index=coupons.index))

# quoted prices are clean; discounted cash flows are worth the dirty (invoice) price
coupons['DIRTY PRICE'] = coupons['PRICE'] + coupons['ACCRUED']

print(coupons[['CUSIP', 'SECURITY TYPE', 'RATE', 'MATURITY DATE', 'PREV COUPON', 'NEXT COUPON',
               'N CASH FLOWS', 'PRICE', 'ACCRUED', 'DIRTY PRICE']].head(10))
print(coupons.groupby('SECURITY TYPE')['TIME TO MATURITY'].describe())

from scipy.optimize import brentq

def ytm(times, amounts, price):
    return brentq(lambda y: (amounts * np.exp(-y * times)).sum() - price, -0.05, 0.30)

coupons['YTM'] = [ytm(t, a, p) for t, a, p in
                  zip(coupons['CF TIMES'], coupons['CF AMOUNTS'], coupons['DIRTY PRICE'])]
coupons['YEARS'] = coupons['TIME TO MATURITY'] / year_day_count
bills['YEARS'] = bills['TIME TO MATURITY'] / year_day_count

plt.figure()
ax = sns.scatterplot(data=coupons, x='YEARS', y='YTM', hue='SECURITY TYPE')
sns.scatterplot(data=bills, x='YEARS', y='ZERO RATE', label='MARKET BASED BILL', ax=ax)
ax.set(title="Observed Treasury Yields - October 14th, 2026",
       xlabel="Time to Maturity (years)",
       ylabel="Yield to maturity (continuously compounded, decimal)")
plt.savefig("10-14-26_yields_observed.png")
